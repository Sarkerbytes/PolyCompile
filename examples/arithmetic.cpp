#include <iostream>
using namespace std;

int main() {
    int a = 15;
    int b = 5;
    int sum = a + b;
    int diff = a - b;
    int prod = a * b;
    int div = a / b;
    cout << "Sum: " << sum << endl;
    cout << "Diff: " << diff << endl;
    cout << "Prod: " << prod << endl;
    cout << "Div: " << div << endl;
    return 0;
}
