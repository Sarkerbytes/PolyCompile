public class Arithmetic {
    public static void main(String[] args) {
        int a = 20;
        int b = 4;
        int sum = a + b;
        int diff = a - b;
        int prod = a * b;
        int div = a / b;
        System.out.println("Sum = " + sum);
        System.out.println("Diff = " + diff);
        System.out.println("Prod = " + prod);
        System.out.println("Div = " + div);
    }
}
